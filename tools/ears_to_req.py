"""Scratch: turn the EARS guards in module docstrings into Sphinx-Needs req needs.

Usage: python ears_to_req.py [--write]
Without --write it prints per-module counts only.
"""
import ast
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "sphinx" / "requirements.rst"
MODULES = [
    ("chunkgraph", "CG", "Chunk graph"),
    ("sparsevec_store", "SV", "Lexical index store"),
    ("ingest_arxiv_sparsevec", "IS", "Lexical index build"),
    ("arxiv_graph_service", "AGS", "Corpus updates"),
    ("section_corpus", "SC", "Section corpus"),
    ("section_embed", "SE", "Section embeddings"),
    ("section_sparse", "SP", "Section sparse vectors"),
    ("section_store", "SS", "Section store"),
    ("arxiv_titles", "AT", "Paper titles"),
    ("summarize_clusters", "SUM", "Community summaries"),
    ("section_query_panel", "QP", "Query panels"),
    ("section_graphrag", "GR", "Question answering"),
    ("arxiv_rag_api", "API", "Retrieval API"),
    ("owui_filter", "OWUI", "Open WebUI filter"),
    ("global_aggregate", "GA", "Global aggregate"),
    ("aggregate_jobs", "AJ", "Aggregate jobs"),
]
GUARD = re.compile(r"^([A-Z]{1,3}\d{1,3})\s+(\S.*)$")


def guards(doc: str):
    out, cur = [], None
    for line in doc.splitlines():
        m = GUARD.match(line)
        if m:
            cur = [m.group(1), m.group(2).strip()]
            out.append(cur)
            continue
        if cur is not None and line[:1] in (" ", "\t") and line.strip():
            cur[1] += " " + line.strip()
            continue
        cur = None
    return out


def safe_title(text: str) -> str:
    t = re.sub(r"[`*|\\<>]", "", text)
    t = re.sub(r"\s+", " ", t).strip()
    cut = t.find(". ")
    if 0 < cut < 110:
        t = t[:cut]
    return t[:110].rstrip(" ,;:")


def main() -> None:
    write = "--write" in sys.argv
    lines = [
        "Requirements",
        "============",
        "",
        "Requirement needs generated from the EARS guards in the module docstrings",
        "(generated by ``tools/ears_to_req.py``). The docstrings remain",
        "the source; regenerate this page after a guard changes.",
        "",
    ]
    total = 0
    for mod, prefix, heading in MODULES:
        path = ROOT / "src" / f"{mod}.py"
        tree = ast.parse(path.read_text(encoding="utf-8"))
        found = guards(ast.get_docstring(tree) or "")
        seen = {}
        print(f"{mod:26s} {len(found):4d}")
        total += len(found)
        if not found:
            continue
        lines += [heading, "-" * len(heading), ""]
        for gid, body in found:
            n = seen.get(gid, 0) + 1
            seen[gid] = n
            rid = f"REQ_{prefix}_{gid}" + (f"_{n}" if n > 1 else "")
            lines += [
                f".. req:: {safe_title(body)}",
                f"   :id: {rid}",
                f"   :tags: {mod}",
                "",
                f"   {body.replace('|', chr(92) + '|')}",
                "",
            ]
    print(f"TOTAL {total}")
    if write:
        OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print("WROTE", OUT)


if __name__ == "__main__":
    main()
